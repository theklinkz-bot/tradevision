interface JobPixelArtProps {
  job: JobClass;
  /** Size of one pixel in SVG units. Default 4 → 80×112px display */
  pixelSize?: number;
  color?: string;
  className?: string;
  style?: React.CSSProperties;
}

export function JobPixelArt({ job, pixelSize = 4, color = 'currentColor', className, style }: JobPixelArtProps) {
  const map = MAPS[job];
  const COLS = 20;
  const ROWS = map.length;

  const rects: React.ReactNode[] = [];
  map.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') {
        rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={color} />);
      }
    }
  });

  return (
    <svg
      viewBox={`0 0 ${COLS} ${ROWS}`}
      width={COLS * pixelSize}
      height={ROWS * pixelSize}
      className={className}
      style={{ imageRendering: 'pixelated', display: 'block', ...style }}
      shapeRendering="crispEdges"
    >
      {rects}
    </svg>
  );
}
